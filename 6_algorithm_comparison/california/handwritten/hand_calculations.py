W("$$z=\\frac{x-\\mu}{\\sigma},\\qquad a_k = w_k z + b_k,\\qquad h_k=\\text{ReLU}(a_k)=\\max(0,a_k),\\qquad \\hat y = v_1h_1+v_2h_2+c$$")
