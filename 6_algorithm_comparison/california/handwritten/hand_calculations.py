W("4. **Backward pass (back-propagation):** use the chain rule to get the gradient of the loss with respect to every weight.")
W("5. **Update** every weight: $w \\leftarrow w - \\eta\\,\\partial L/\\partial w$. Repeat for many epochs until the loss stops falling.")
W("")
