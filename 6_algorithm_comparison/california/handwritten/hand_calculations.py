def metrics(pred):
    e = yt - pred
    mae = np.mean(np.abs(e)); mse = np.mean(e ** 2); rmse = np.sqrt(mse)
    r2 = 1 - np.sum(e ** 2) / np.sum((yt - yt.mean()) ** 2)
    return mae, mse, rmse, r2


def sse(v):
    return float(np.sum((v - v.mean()) ** 2)) if len(v) else 0.0


def best_split(Xn, yn, features=(0, 1), min_leaf=1):
    """Exhaustive CART search; returns list of candidate rows and the best one."""
    cands = []
    for j in features:
        vals = np.unique(Xn[:, j])
        for a, b in zip(vals[:-1], vals[1:]):
            t = (a + b) / 2
            L, R = yn[Xn[:, j] <= t], yn[Xn[:, j] > t]
            if len(L) < min_leaf or len(R) < min_leaf:
                continue
            cands.append(dict(j=j, t=t, nL=len(L), nR=len(R), mL=L.mean(), mR=R.mean(),
                              sL=sse(L), sR=sse(R), tot=sse(L) + sse(R)))
    best = min(cands, key=lambda c: c["tot"])
    return cands, best


