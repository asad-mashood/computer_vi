W("## 4. Neural Network Regression (Multi-Layer Perceptron)")
W("")
W("### Working procedure")
W("1. **Scale the inputs** (z-score) — gradient descent works badly on features with different ranges.")
W("2. **Forward pass:** each neuron computes a weighted sum plus bias, then a non-linear activation (ReLU). The output neuron is linear (regression).")
